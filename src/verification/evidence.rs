use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use uuid::Uuid;

// ─────────────────────────────────────────────────────────
//  Core evidence types — the heart of the differentiator
// ─────────────────────────────────────────────────────────

/// A concrete piece of evidence produced during the agent run.
/// Every artifact is content-addressed via its SHA-256 hash.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Artifact {
    pub id: String,
    pub kind: ArtifactKind,
    pub content: String,
    pub sha256: String,
    pub created_at: DateTime<Utc>,
    /// Optional external URL (e.g., Tavily source, GitHub commit).
    pub source_url: Option<String>,
}

/// What type of evidence this artifact represents.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum ArtifactKind {
    /// Unified diff of code changes.
    CodeDiff,
    /// Raw output from `cargo test`.
    TestOutput,
    /// Raw output from `cargo clippy`.
    ClippyOutput,
    /// Raw output from `cargo check`.
    CheckOutput,
    /// Tavily search result used to ground a decision.
    TavilySource,
    /// The plan generated by the LLM.
    AgentPlan,
    /// The LLM prompt/response pair.
    LlmInteraction,
    /// The final generated code.
    GeneratedCode,
    /// Arbitrary log or metadata.
    Log,
}

impl ArtifactKind {
    pub fn label(&self) -> &'static str {
        match self {
            Self::CodeDiff => "Code Diff",
            Self::TestOutput => "Test Output",
            Self::ClippyOutput => "Clippy Output",
            Self::CheckOutput => "Check Output",
            Self::TavilySource => "Tavily Source",
            Self::AgentPlan => "Agent Plan",
            Self::LlmInteraction => "LLM Interaction",
            Self::GeneratedCode => "Generated Code",
            Self::Log => "Log",
        }
    }

    pub fn emoji(&self) -> &'static str {
        match self {
            Self::CodeDiff => "📝",
            Self::TestOutput => "✅",
            Self::ClippyOutput => "📎",
            Self::CheckOutput => "🔨",
            Self::TavilySource => "🔍",
            Self::AgentPlan => "📋",
            Self::LlmInteraction => "🤖",
            Self::GeneratedCode => "💻",
            Self::Log => "📄",
        }
    }
}

/// A claim the agent makes (e.g., "All tests pass").
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Claim {
    pub id: String,
    pub statement: String,
    pub category: ClaimCategory,
    pub verified: VerificationStatus,
    pub created_at: DateTime<Utc>,
}

/// High-level categories for agent claims.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum ClaimCategory {
    TestsPassing,
    NoCompileErrors,
    NoClippyWarnings,
    CodeChangeCorrect,
    BasedOnDocumentation,
    Custom(String),
}

impl ClaimCategory {
    pub fn label(&self) -> String {
        match self {
            Self::TestsPassing => "Tests Passing".into(),
            Self::NoCompileErrors => "No Compile Errors".into(),
            Self::NoClippyWarnings => "No Clippy Warnings".into(),
            Self::CodeChangeCorrect => "Code Change Correct".into(),
            Self::BasedOnDocumentation => "Based on Documentation".into(),
            Self::Custom(s) => s.clone(),
        }
    }
}

/// Whether a claim has been verified against its evidence.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum VerificationStatus {
    /// Artifact confirms the claim.
    Verified,
    /// Artifact contradicts the claim.
    Refuted,
    /// No matching artifact found; claim is unsubstantiated.
    Unverified,
    /// Verification could not be performed (e.g., sandbox down).
    Skipped,
}

impl VerificationStatus {
    pub fn emoji(&self) -> &'static str {
        match self {
            Self::Verified => "✅",
            Self::Refuted => "❌",
            Self::Unverified => "⚠️",
            Self::Skipped => "⏭️",
        }
    }

    pub fn label(&self) -> &'static str {
        match self {
            Self::Verified => "VERIFIED",
            Self::Refuted => "REFUTED",
            Self::Unverified => "UNVERIFIED",
            Self::Skipped => "SKIPPED",
        }
    }
}

/// Links a claim to the artifacts that support or refute it.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EvidenceLink {
    pub claim_id: String,
    pub artifact_id: String,
    pub relationship: EvidenceRelationship,
    pub explanation: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum EvidenceRelationship {
    /// This artifact directly supports the claim.
    Supports,
    /// This artifact contradicts the claim.
    Contradicts,
    /// This artifact is related context but doesn't prove/disprove.
    Context,
}

/// The complete verification report for an agent run.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VerificationReport {
    pub run_id: String,
    pub issue_url: String,
    pub issue_title: String,
    pub created_at: DateTime<Utc>,
    pub claims: Vec<Claim>,
    pub artifacts: Vec<Artifact>,
    pub evidence_links: Vec<EvidenceLink>,
    pub summary: ReportSummary,
}

/// Aggregate statistics for the report.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReportSummary {
    pub total_claims: usize,
    pub verified: usize,
    pub refuted: usize,
    pub unverified: usize,
    pub skipped: usize,
    pub trust_score: f64,
}

// ─────────────────────────────────────────────────────────
//  Factory / helper methods
// ─────────────────────────────────────────────────────────

impl Artifact {
    /// Create a new artifact with auto-generated ID and SHA-256 hash.
    pub fn new(kind: ArtifactKind, content: impl Into<String>, source_url: Option<String>) -> Self {
        let content = content.into();
        let sha256 = compute_sha256(&content);
        Self {
            id: Uuid::new_v4().to_string(),
            kind,
            content,
            sha256,
            created_at: Utc::now(),
            source_url,
        }
    }
}

impl Claim {
    /// Create a new unverified claim.
    pub fn new(statement: impl Into<String>, category: ClaimCategory) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            statement: statement.into(),
            category,
            verified: VerificationStatus::Unverified,
            created_at: Utc::now(),
        }
    }
}

impl EvidenceLink {
    pub fn supports(
        claim_id: impl Into<String>,
        artifact_id: impl Into<String>,
        explanation: impl Into<String>,
    ) -> Self {
        Self {
            claim_id: claim_id.into(),
            artifact_id: artifact_id.into(),
            relationship: EvidenceRelationship::Supports,
            explanation: explanation.into(),
        }
    }

    pub fn contradicts(
        claim_id: impl Into<String>,
        artifact_id: impl Into<String>,
        explanation: impl Into<String>,
    ) -> Self {
        Self {
            claim_id: claim_id.into(),
            artifact_id: artifact_id.into(),
            relationship: EvidenceRelationship::Contradicts,
            explanation: explanation.into(),
        }
    }
}

impl ReportSummary {
    /// Compute summary statistics from a list of claims.
    pub fn from_claims(claims: &[Claim]) -> Self {
        let total = claims.len();
        let verified = claims
            .iter()
            .filter(|c| c.verified == VerificationStatus::Verified)
            .count();
        let refuted = claims
            .iter()
            .filter(|c| c.verified == VerificationStatus::Refuted)
            .count();
        let unverified = claims
            .iter()
            .filter(|c| c.verified == VerificationStatus::Unverified)
            .count();
        let skipped = claims
            .iter()
            .filter(|c| c.verified == VerificationStatus::Skipped)
            .count();

        let trust_score = if total > 0 {
            verified as f64 / total as f64 * 100.0
        } else {
            0.0
        };

        Self {
            total_claims: total,
            verified,
            refuted,
            unverified,
            skipped,
            trust_score,
        }
    }
}

/// Compute SHA-256 hex digest of content.
pub fn compute_sha256(content: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(content.as_bytes());
    hex::encode(hasher.finalize())
}
